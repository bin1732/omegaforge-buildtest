"""L0 归一化：任何"用于安全判断"的文本都必须先过这一层。

为什么必须有
------------
安全判断跑在**原始字节**上，等于把判定权交给了攻击者的排版选择。
例如：

    rm -rf /            -> blocked=True
    r<U+200B>m -rf /    -> blocked=False   ← 一个零宽字符，底线失效
    c<U+0430>t ~/.ssh/id_rsa -> blocked=False   ← 西里尔 а 冒充拉丁 a
    ｃａｔ ~/.ssh/id_rsa       -> blocked=False   ← 全角

最后两例在 POSIX shell 下未必真能执行，但危害不依赖执行：
1) **审批欺骗**：界面渲染出的 `cat ~/.ssh/id_rsa` 与真实字节不同，
   用户批准的是他看到的那个，执行的可能是另一个。
2) **审计失真**：审计链记的是变形文本，事后回溯与取证对不上。

因此归一化的目标不是"让命令能跑"，而是**让判断看到的文本与人类
看到的文本一致**——这是所有下游检测（危险命令、注入扫描、critical
清单、规则匹配）的共同前置。

三条边界（刻意不做）
--------------------
- **不做中文简繁转换**：`後`→`后` 会改变语义，`后的` 与 `後的` 在中文里
  都可能合法出现。且需引入词库，与"本地零依赖"冲突。留给 L2 语义层。
- **不做拼音/拆字还原**：那是内容审核（小花）的领域，不是命令门禁。
- **不用于回显给用户**：归一化只供判定使用，展示/执行仍用原文，
  避免"判断说安全、执行是原文"的二次偏移——所以调用方必须把
  归一化结果用于判定，把原文用于展示，两者都在审计里留痕。
"""
from __future__ import annotations

import re
import unicodedata

# ----------------------------------------------------------- 不可见字符
# 零宽、软连字符、bidi 控制符、BOM。这些字符在渲染上"不存在"，
# 却能改变字符串的实际内容——是判定与观感错位的第一来源。
_INVISIBLE = (
    "\u200b",  # ZERO WIDTH SPACE
    "\u200c",  # ZWNJ
    "\u200d",  # ZWJ
    "\u200e",  # LRM
    "\u200f",  # RLM
    "\u202a", "\u202b", "\u202c", "\u202d", "\u202e",  # bidi 嵌入/覆写
    "\u2060",  # WORD JOINER
    "\u2066", "\u2067", "\u2068", "\u2069",            # bidi isolate
    "\ufeff",  # BOM / ZWNBSP
    "\u00ad",  # SOFT HYPHEN
    "\u180e",  # MONGOLIAN VOWEL SEPARATOR
    "\u2061", "\u2062", "\u2063", "\u2064",  # 不可见数学运算符
)

_INVISIBLE_RE = re.compile("[" + "".join(_INVISIBLE) + "]")

# ----------------------------------------------------------- 同形字
# 只收"视觉上极易混淆且常见"的字符，按**形状**映射到拉丁字母。
# 刻意不收需要语义判断的（如西里尔 н 形似 H 但音为 n），
# 宁可漏收，不可误改——误改会把合法命令判成危险命令。
_HOMOGLYPHS = {
    # 西里尔小写
    "\u0430": "a", "\u0435": "e", "\u043e": "o", "\u0440": "p",
    "\u0441": "c", "\u0443": "y", "\u0445": "x", "\u0456": "i",
    "\u0458": "j", "\u0455": "s", "\u04bb": "h", "\u04cf": "l",
    "\u045b": "q", "\u0453": "g", "\u04ae": "Y", "\u04bd": "v",
    # 西里尔大写
    "\u0410": "A", "\u0412": "B", "\u0415": "E", "\u041a": "K",
    "\u041c": "M", "\u041d": "H", "\u041e": "O", "\u0420": "P",
    "\u0421": "C", "\u0422": "T", "\u0425": "X", "\u0406": "I",
    "\u0408": "J", "\u0405": "S",
    # 希腊
    "\u03bf": "o", "\u03bd": "v", "\u03c4": "t", "\u03b1": "a",
    "\u03b5": "e", "\u03b9": "i", "\u03ba": "k", "\u03c1": "p",
    "\u03c3": "s", "\u03c5": "u", "\u03b3": "y", "\u03c7": "x",
    "\u039f": "O", "\u039d": "N", "\u03a4": "T", "\u0391": "A",
    "\u0392": "B", "\u0395": "E", "\u039a": "K", "\u039c": "M",
    "\u03a1": "P", "\u03a3": "S", "\u03a5": "Y", "\u03a7": "X",
    # 全角/数学字母数字由 NFKC 处理，此处不重复
}

_HOMOGLYPH_RE = re.compile("[" + "".join(_HOMOGLYPHS) + "]")


def normalize(text: str) -> str:
    """归一化到"人类看到的形式"，供安全判定使用。

    顺序不可调换：先 NFKC（把全角/兼容字符折叠），再剥不可见字符
    （NFKC 不会移除零宽），最后替换同形字（必须在前两步之后，否则
    全角西里尔字符会漏网）。
    """
    s = str(text or "")
    # 1) 兼容折叠：全角 ASCII、数学字母、上标等
    s = unicodedata.normalize("NFKC", s)
    # 2) 剥离不可见字符
    s = _INVISIBLE_RE.sub("", s)
    # 3) 同形字按形状折叠
    s = _HOMOGLYPH_RE.sub(lambda m: _HOMOGLYPHS[m.group(0)], s)
    return s


def differs_from_raw(text: str) -> bool:
    """归一化是否改变了原文。用于审计：判定依据与原文不一致时必须留痕，
    否则事后无法解释"为什么这条被拦/被放"。"""
    return normalize(text) != str(text or "")
