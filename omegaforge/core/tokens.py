"""token 估算的唯一真源。

为什么必须有唯一真源
--------------------
（端到端，人设 8000 字 + 20 条长历史）：同一段文本在两个模块里被估成
两个数——server 用 1.2/汉字，chat.store 用 1.0/汉字。于是出现**预算裁剪与
最终校验互相打架**：

  * build_context 按 1.0 裁剪，认为"已装到 23,169，没超 24,000"；
  * server 随后按 1.2 复核，得到 26,498 → 判定超预算并报错。

后果不是"报错太多"这么简单，而是**优雅降级被静默降级成硬失败**：本该
"丢掉最旧的历史、对话继续"，结果变成"整句发不出去，请精简人设"。用户
拿到的指引（去改技能文件）是错的——真正该丢的是历史，而历史已经在裁剪
里被处理过了，只是两边算的不一样。

所以这里收敛成**单一实现**，且取两者中较保守的 1.2：对预算而言，估高
意味着少装、估低意味着超发——超发会被上游拒收（400 context length），
并被映射成 500「模型服务返回了异常响应」。宁可少装。

真实计费仍以 UsageStore 记录的上游返回值为准，本函数只用于预估与裁剪。
"""
from __future__ import annotations

# 汉字在主流分词器下常占 1~2 个 token，取 1.2 是保守值（估高不估低）。
CJK_PER_CHAR = 1.2
# 西文按 4 字符 1 token 粗估。
LATIN_PER_CHAR = 0.25


def estimate_tokens(text: str | None) -> int:
    """估算 token 数：CJK 每字 1.2，其余按 4 字符 1 token。

    对空值返回 0，绝不为负——负数会让"预算 - 已用"算出比预算更大的剩余，
    从而让裁剪逻辑认为怎么装都装得下。
    """
    if not text:
        return 0
    cjk = sum(1 for ch in text if 0x4E00 <= ord(ch) <= 0x9FFF)
    return int(cjk * CJK_PER_CHAR + (len(text) - cjk) * LATIN_PER_CHAR) + 1
